"""Generate docs/data_dictionary.md (from the database comments) and docs/tools.md (from the tool code).

    python scripts/gen_docs.py
"""

import inspect
import sys
import typing
from pathlib import Path

import psycopg

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from mr_assistant import tools                     # noqa: E402
from mr_assistant.config import get_settings       # noqa: E402

COLUMNS = """
SELECT c.table_schema, c.table_name, c.column_name, c.data_type, c.udt_name, c.is_nullable,
       col_description(format('%I.%I', c.table_schema, c.table_name)::regclass, c.ordinal_position) AS description
FROM information_schema.columns c
WHERE c.table_schema IN ('core', 'analytics')
ORDER BY c.table_schema, c.table_name, c.ordinal_position
"""
OBJECTS = """
SELECT n.nspname AS schema, c.relname AS name, c.relkind, obj_description(c.oid) AS description,
       c.relrowsecurity AS rls
FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname IN ('core', 'analytics') AND c.relkind IN ('r', 'v')
ORDER BY n.nspname, c.relname
"""
ORDER = ["calendar_day", "business_unit", "geography", "employee", "product", "content", "doctor", "clinic",
         "chemist", "mcl", "tour_plan", "kpi_target", "dcr_call", "dcr_call_product", "call_note", "rcpa_entry",
         "doctor_brand_plan", "formulary_listing", "communication", "nba_recommendation", "agent_action_log"]
AUDIT = {"created_at", "updated_at", "source_system", "load_batch_id"}


def type_name(r):
    t = r["udt_name"].lstrip("_") + ("[]" if r["data_type"] == "ARRAY" else "")
    return {"int8": "bigint", "int4": "integer", "int2": "smallint", "float8": "double", "bool": "boolean",
            "timestamptz": "timestamptz", "text": "text"}.get(t, t)


def data_dictionary(conn) -> str:
    cols, objs = {}, {}
    for r in conn.execute(COLUMNS):
        cols.setdefault((r["table_schema"], r["table_name"]), []).append(r)
    for r in conn.execute(OBJECTS):
        objs[(r["schema"], r["name"])] = r
    out = ["# Data dictionary", "",
           "Generated by `scripts/gen_docs.py` from the comments in the database (`db/comments.sql`).",
           "Schema `core` holds the 21 tables (silver layer); schema `analytics` holds the gold views.",
           "Every `core` table also has the audit columns `created_at`, `updated_at`, `source_system`, `load_batch_id`.",
           "RLS = row-level security: rows are filtered to the current user's territory or team.", "",
           "## Tables (`core`)", "", "| Table | RLS | Description |", "|---|---|---|"]
    for t in ORDER:
        o = objs[("core", t)]
        out.append(f"| [`{t}`](#core{t.replace('_', '')}) | {'yes' if o['rls'] else 'no'} | {o['description'] or ''} |")
    out += ["", "## Views (`analytics`)", "", "| View | Description |", "|---|---|"]
    views = sorted(k[1] for k, o in objs.items() if k[0] == "analytics")
    for v in views:
        out.append(f"| [`{v}`](#analytics{v.replace('_', '')}) | {objs[('analytics', v)]['description'] or ''} |")
    for schema, names in (("core", ORDER), ("analytics", views)):
        for t in names:
            out += ["", f"### {schema}.{t}", "", objs[(schema, t)]["description"] or "", "",
                    "| Column | Type | Null | Description |", "|---|---|---|---|"]
            for r in cols[(schema, t)]:
                if schema == "core" and r["column_name"] in AUDIT:
                    continue
                out.append(f"| `{r['column_name']}` | {type_name(r)} | {'yes' if r['is_nullable'] == 'YES' else 'no'} "
                           f"| {r['description'] or ''} |")
    return "\n".join(out) + "\n"


def _type_str(tp) -> str:
    """Readable type for markdown tables: `int, optional`, `list[PriorityDoctor]` (no pipes, no module paths)."""
    args = typing.get_args(tp)
    origin = typing.get_origin(tp)
    if not args:
        return getattr(tp, "__name__", str(tp))
    if type(None) in args:
        rest = [a for a in args if a is not type(None)]
        return f"{_type_str(rest[0])}, optional"
    return f"{getattr(origin, '__name__', str(origin))}[{', '.join(_type_str(a) for a in args)}]"


def tool_catalog() -> str:
    groups = {}
    for f in tools.ALL_TOOLS:
        groups.setdefault(f.__module__.rsplit(".", 1)[-1], []).append(f)
    out = ["# Tool catalog", "",
           "Generated by `scripts/gen_docs.py` from `src/mr_assistant/tools/`.",
           "All tools are read-only and take `db` (from `as_employee(employee_id)`) as the first argument;",
           "row-level security decides what each user sees. Errors raise `ToolError` / `NotFound` with a",
           "message that can be shown to the user as-is.", "",
           "```python", "from mr_assistant.db import as_employee", "from mr_assistant import tools", "",
           "with as_employee(990001) as db:      # BO Karthikeyan R, Chennai",
           "    tools.get_pending_visits(db, limit=5)", "```", "",
           f"{len(tools.ALL_TOOLS)} tools:", ""]
    out += ["| Group | Tool | Purpose |", "|---|---|---|"]
    for g, fs in groups.items():
        for f in fs:
            out.append(f"| {g} | [`{f.__name__}`](#{f.__name__.replace('_', '')}) | "
                       f"{inspect.getdoc(f).split(chr(10) + chr(10))[0].replace(chr(10), ' ')} |")
    for g, fs in groups.items():
        out += ["", f"## {g.capitalize()}"]
        for f in fs:
            sig = inspect.signature(f)
            params = [p for p in sig.parameters.values() if p.name != "db"]
            hints = typing.get_type_hints(f)
            ret = hints.get("return")
            model = typing.get_args(ret)[0] if typing.get_args(ret) else ret
            out += ["", f"### {f.__name__}", "", inspect.getdoc(f), "", "**Parameters**", ""]
            if params:
                out += ["| Name | Type | Default |", "|---|---|---|"]
                for p in params:
                    default = "required" if p.default is inspect.Parameter.empty else repr(p.default)
                    out.append(f"| `{p.name}` | {_type_str(hints.get(p.name, ''))} | {default} |")
            else:
                out.append("None (besides `db`).")
            out += ["", f"**Returns** `{_type_str(ret)}` with fields: "
                    + ", ".join(f"`{n}`" for n in getattr(model, "model_fields", {}))]
    return "\n".join(out) + "\n"


def main() -> None:
    with psycopg.connect(get_settings().app_conninfo, row_factory=psycopg.rows.dict_row) as conn:
        (ROOT / "docs" / "data_dictionary.md").write_text(data_dictionary(conn))
    (ROOT / "docs" / "tools.md").write_text(tool_catalog())
    print("wrote docs/data_dictionary.md and docs/tools.md")


if __name__ == "__main__":
    main()
